/**
 * Shape the Amharic bundle must satisfy.
 *
 * Note this is deliberately NOT `typeof en` with `as const`: literal types
 * would require the Amharic file to repeat the English strings verbatim. What
 * we want to enforce is the *key set* — every key present, nothing extra,
 * every value a string. A missing Amharic key is then a build error rather
 * than a silent English fallback in production (AUDIT.md §H1).
 */
type Localized<T> = { [K in keyof T]: T[K] extends string ? string : Localized<T[K]> };

export type TranslationSchema = Localized<typeof en>;
